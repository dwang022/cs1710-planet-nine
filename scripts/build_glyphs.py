#!/usr/bin/env python3
"""Write src/glyphs.js: the few letters the drawings use, traced from Space Grotesk as paths.

The site's text is set in Space Grotesk (src/fonts.js), but the drawings in src/art.js
are also exported as standalone files (public/art/, the favicon), where no web font can
load. Tracing the letters they need, Planet Nine's question mark and the lockup's two
lines, keeps them the same shape everywhere.

Needs fontTools (pip install fonttools). The font, under the SIL Open Font License, is
downloaded from the Google Fonts repository, or read from a path given as the argument.

  python -P scripts/build_glyphs.py [SpaceGrotesk[wght].ttf]
  node scripts/export_art.mjs
"""
import os, sys, tempfile, urllib.request
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "glyphs.js")
URL = "https://github.com/google/fonts/raw/main/ofl/spacegrotesk/SpaceGrotesk%5Bwght%5D.ttf"

# What to trace: name -> (text, weight, letter-spacing in em, anchor). The spacings are the
# lockup's in src/art.js (3.2 at 11 px, 2.6 at 28 px), so the traced words keep its look.
GLYPHS = {
    "QMARK": ("?", 700, 0, "middle"),
    "LOCKUP_TOP": ("THE SEARCH FOR", 600, 3.2 / 11, "start"),
    "LOCKUP_BOTTOM": ("PLANET NINE", 700, 2.6 / 28, "start"),
}


def num(v):
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def trace(font, text, spacing, anchor):
    """The text as one path in ems: baseline at y = 0, y down, starting (or centred) at x = 0."""
    upm = font["head"].unitsPerEm
    glyphs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]
    names = [cmap[ord(ch)] for ch in text]
    widths = [hmtx[n][0] / upm for n in names]
    x = -sum(widths) / 2 if anchor == "middle" else 0
    pen = SVGPathPen(glyphs, ntos=num)
    for name, w in zip(names, widths):
        glyphs[name].draw(TransformPen(pen, (1 / upm, 0, 0, -1 / upm, x, 0)))
        x += w + spacing
    return pen.getCommands()


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else None
    if not path:
        path = os.path.join(tempfile.mkdtemp(prefix="p9-font-"), "SpaceGrotesk-wght.ttf")
        urllib.request.urlretrieve(URL, path)
    out = []
    for name, (text, weight, spacing, anchor) in GLYPHS.items():
        font = instantiateVariableFont(TTFont(path), {"wght": weight})
        d = trace(font, text, spacing, anchor)
        out.append(f"// {text!r}, weight {weight}" + (f", letter-spaced {spacing:.3f} em" if spacing else "")
                   + (", centred on x = 0" if anchor == "middle" else "") + f"\nexport const {name} = '{d}'\n")
        print(f"  {name:<14} {len(d):>5} chars  {text!r}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by scripts/build_glyphs.py from Space Grotesk (SIL Open Font License); do not edit.\n"
                "// Each path is in ems with its baseline at y = 0: translate it to the baseline and scale it\n"
                "// by the font size. Traced, not typed, so exported drawings keep the letters without the font.\n\n"
                + "\n".join(out))
    print(f"wrote {OUT}")


main()
