#!/usr/bin/env python3
"""Scale each schematic survey footprint so its solid angle matches the area the
survey actually published.

The footprints in surveys.json are declination bands crossed with RA ranges -
a deliberate simplification. That was harmless while the map only showed "who
looked roughly where". It stops being harmless once the map shades by depth and
lets the deepest survey win a patch of sky, because the two deepest surveys are
exactly the ones whose schematic bands are far too generous: Subaru HSC's band
covers 5.8x its real area.

So: keep the band's centre and its RA ranges, and squeeze the declination range
until the area comes out right. The shape stays schematic; the amount of sky it
claims becomes honest.
"""
import json, math, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, "data", "processed", "surveys.json")


def solid_angle(dec_range, ra_ranges):
    d0, d1 = [math.radians(d) for d in dec_range]
    band = math.sin(d1) - math.sin(d0)
    frac_ra = sum(r1 - r0 for r0, r1 in ra_ranges) / 360.0
    return band * frac_ra * 2 * math.pi * (180 / math.pi) ** 2


def squeeze(dec_range, ra_ranges, target):
    """Shrink (or grow) the band about its centre until it matches `target`."""
    lo, hi = dec_range
    centre = (lo + hi) / 2
    half = (hi - lo) / 2
    best = (lo, hi)
    for _ in range(80):
        mid = half / 2 if solid_angle((centre - half, centre + half), ra_ranges) > target else half
        # simple bisection on the half-width
        a, b = 0.0, half
        for _ in range(60):
            m = (a + b) / 2
            if solid_angle((max(-90, centre - m), min(90, centre + m)), ra_ranges) < target:
                a = m
            else:
                b = m
        best = (max(-90, centre - b), min(90, centre + b))
        break
    return [round(best[0], 3), round(best[1], 3)]


def main():
    doc = json.load(open(PATH))
    print(f"{'survey':<34}{'declared':>10}{'before':>10}{'after':>10}")
    for s in doc["surveys"]:
        if not s.get("dec_range") or not s.get("ra_ranges"):
            continue
        area = s.get("area_sq_deg")
        before = solid_angle(s["dec_range"], s["ra_ranges"])
        if not area:
            # No verified area, so we cannot honestly calibrate it. Flag it; the
            # map leaves these out of the depth shading.
            s["footprint_area_verified"] = False
            print(f"{s['name'][:33]:<34}{'(none)':>10}{before:>10,.0f}{'skipped':>10}")
            continue
        s["dec_range_calibrated"] = squeeze(s["dec_range"], s["ra_ranges"], area)
        s["footprint_area_verified"] = True
        after = solid_angle(s["dec_range_calibrated"], s["ra_ranges"])
        print(f"{s['name'][:33]:<34}{area:>10,}{before:>10,.0f}{after:>10,.0f}")

    doc["_footprint_calibration"] = (
        "dec_range is the raw schematic band. dec_range_calibrated squeezes that "
        "band about its centre so its solid angle matches area_sq_deg, which the "
        "depth-shaded map uses. Surveys with footprint_area_verified = false have "
        "no published area we could confirm and are excluded from depth shading. "
        "Generated by scripts/calibrate_footprints.py.")
    json.dump(doc, open(PATH, "w"), indent=1)


main()
